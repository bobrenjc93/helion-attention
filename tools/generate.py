def strip_helion(code: str) -> str:
    """Rewrite Helion's generated module into a Helion-free one."""
    for needle, replacement in _SUBSTITUTIONS:
        code = code.replace(needle, replacement)
    leftover = re.findall(r"^.*(?:\bhelion\b|_source_module).*$", code, flags=re.MULTILINE)
    leftover = [line for line in leftover if not line.lstrip().startswith("#")]
    if leftover:
        raise RuntimeError("unhandled Helion reference in generated code:\n" + "\n".join(leftover))
    return code


def rename_entry_point(
    code: str, generated_name: str, stable_name: str = "attention"
) -> str:
    """Expose a generated host wrapper under a stable runtime name."""
    pattern = rf"^def {re.escape(generated_name)}\("
    if not re.search(pattern, code, flags=re.MULTILINE):
        raise RuntimeError(f"generated code has no `def {generated_name}(`")
    return re.sub(
        pattern, f"def {stable_name}(", code, count=1, flags=re.MULTILINE
    )


def namespace_generated_constants(code: str, prefix: str) -> str:
    """Keep module-level constexpr names distinct when composing two kernels."""
    names = re.findall(r"^(_[A-Z][A-Z0-9_]*)\s*=", code, flags=re.MULTILINE)
    for name in names:
        code = re.sub(rf"\b{re.escape(name)}\b", f"_{prefix}{name}", code)
    return code


def merge_generated_modules(*modules: str) -> str:
    """Combine standalone Helion outputs under one future import."""
    bodies = []
    for module in modules:
        first, body = module.split("\n", 1)
        if first != "from __future__ import annotations":
            raise RuntimeError("generated module has an unexpected header")
        bodies.append(body)
    return "from __future__ import annotations\n" + "\n".join(bodies)


def _replace_generated_once(
    code: str, old: str, new: str, *, description: str
) -> str:
    """Apply one required generated-code rewrite or fail regeneration loudly."""
    count = code.count(old)
    if count != 1:
        raise RuntimeError(
            f"expected one {description} in generated code, found {count}"
        )
    return code.replace(old, new, 1)


